use light_core::{Clock, Idle};

/// The clock frequencies the runtime configured, passed in by the shell that knows them rather
/// than assumed here. pico-sdk's defaults are 125 MHz for both on the RP2040, 150 MHz on the
/// RP2350.
#[derive(Clone, Copy, Debug)]
pub struct Clocks {
        pub sys_hz: u32,
        pub peri_hz: u32,
}

/// Microseconds since boot from the 64-bit system timer, which pico-sdk's runtime has already
/// started. The RP2350 has two timer blocks and calls the first TIMER0; the RP2040 has one.
///
/// Read as two halves, re-read until the high half is stable across the low read -- the same
/// dance pico-sdk's `time_us_64()` does, without the latching TIMELR/TIMEHR pair, which is
/// per-core state and would race the other core's use of it.
pub fn now_us() -> u64 {
        #[cfg(feature = "rp2040")]
        let timer = unsafe { &*pac::TIMER::ptr() };
        #[cfg(feature = "rp2350")]
        let timer = unsafe { &*pac::TIMER0::ptr() };
        loop {
                let hi = timer.timerawh().read().bits();
                let lo = timer.timerawl().read().bits();
                if timer.timerawh().read().bits() == hi {
                        return ((hi as u64) << 32) | lo as u64;
                }
        }
}

/// The system timer as a [`Clock`].
#[derive(Clone, Copy, Default)]
pub struct SysClock;

impl Clock for SysClock {
        fn now_us(&self) -> u64 {
                now_us()
        }
}

/// What the runtime does between idle passes on this chip: nothing that could miss a deadline.
/// The poll-driven drivers keep their own cadences and no interrupt is guaranteed to wake a
/// `wfe`, so this is a breath, not a sleep. A real low-power idle needs a tick to wake on.
#[derive(Clone, Copy, Default)]
pub struct Breathe;

impl Idle for Breathe {
        fn idle(&mut self) {
                core::hint::spin_loop();
        }
}

/// Cycle a peripheral's reset -- or just release it -- and wait for it to come out. `set` and
/// `clear` are the reset register's field writers for the block (`|w| w.uart0().set_bit()`);
/// `done` reads its bit of `RESET_DONE`.
///
/// IN A CRITICAL SECTION, because the reset register is read-modify-written and the two cores
/// construct peripherals at the same moment at boot -- core 1 its console UART, core 0 everything
/// else. Unserialised, one core's write-back carries the other's stale reset bit, and the block
/// that core is configuring is back in reset under it: a bus fault on its first register read,
/// and with the fault handler in flash, a locked core. It showed as the console dying in the
/// first second, one boot in a few.
pub(crate) fn reset_cycle<S, C, D>(pulse: bool, set: S, clear: C, done: D)
where
        S: FnOnce(&mut pac::resets::reset::W) -> &mut pac::resets::reset::W,
        C: FnOnce(&mut pac::resets::reset::W) -> &mut pac::resets::reset::W,
        D: Fn(&pac::resets::reset_done::R) -> bool,
{
        // SAFETY: the reset block's registers, under the cross-core lock every port path shares
        let resets = unsafe { &*pac::RESETS::ptr() };
        critical_section::with(|_| {
                if pulse {
                        resets.reset().modify(|_, w| set(w));
                }
                resets.reset().modify(|_, w| clear(w));
        });
        while !done(&resets.reset_done().read()) {}
}
