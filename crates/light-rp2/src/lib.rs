//! RP2-family port of the light framework: the RP2040 and the RP2350, one source.
//!
//! Peripherals are driven through the chip's pac register definitions rather than through
//! pico-sdk calls: pico-sdk's peripheral API is mostly `static inline` in headers, which no
//! binding generator can export, so every SDK call from Rust would need a hand-written C shim.
//! The pac reaches everything the framework needs. pico-sdk stays in charge of
//! the RUNTIME (crt0, boot2, clocks, timer start, multicore, USB) in the C shell that links this.
//!
//! One crate for both chips because the blocks this crate touches -- SIO, pads, IO, SPI, I2C,
//! DMA, PWM, the timer -- are the same silicon IP on both, and the two pacs (`rp2040-pac`,
//! `rp235x-pac`) were generated by the same svd2rust generation, so the accessors are
//! identical. The chip is a cargo feature (`rp2040` or `rp2350`, exactly one) and shows in
//! three places: the `pac` alias below, the timer block's name, and the RP2350's pad isolation
//! bit. The Cortex-M0+ adds a fourth, invisible here: it has no atomic read-modify-write
//! instructions, so the framework's atomics are `portable-atomic`'s, which fall back to this
//! crate's critical section on that core and compile to the native instructions on the others.
//!
//! This crate stops at the CHIP. What is soldered to it -- panels, keys, expansion boards --
//! is board wiring, and that belongs to the application: each app carries a `board` module
//! that names its pins, calls the unsafe constructors below exactly once behind a taken-once
//! gate, and hands the peripherals over as an owned set. The framework does not know or care
//! which board anyone runs.

